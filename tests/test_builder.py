def test_a_realistic_document_compiles() -> None:
    d = CppDocBuilder(
        "Ring",
        description="a fixed-capacity ring buffer",
        namespaces=["Demo"],
        tool_name="ring-gen",
    )
    d.lines("using U32 = unsigned int;")
    d.include("Ring.hpp", output=Output.CPP)

    with d.namespace("Demo") as ns:
        with ns.class_("Ring", comment="A ring buffer of fixed capacity") as c:
            with c.public("Types"):
                status = c.enum_class(
                    "Status", underlying="U32", comment="Result codes"
                )
                status.constant("OK", 0, comment="Accepted")
                status.constant("FULL", 1, comment="At capacity")

            with c.public("Constructors and destructors"):
                ctor = c.constructor(explicit=True, comment="Build an empty ring")
                ctor.param("U32", "capacity", comment="The capacity")
                ctor.init("m_head(0)", "m_size(0)", "m_capacity(capacity)")
                c.constructor(params=[("const Ring&", "other")], deleted=True)
                c.destructor(defaulted=True)

            with c.public("Public member functions"):
                push = c.function("push", ret=status.type, comment="Append an item")
                push.param("U32", "item", comment="The item")
                with push.body as b:
                    with b.if_("m_size == m_capacity"):
                        b.line("return Status::FULL;")
                    b.line("m_data[(m_head + m_size) % CAPACITY] = item;")
                    b.line("m_size++;")
                    b.line("return Status::OK;")

                c.function(
                    "size", ret="U32", const=True, inline=True, body="return m_size;"
                )

                describe = c.function("describe", const=True)
                with describe.body as b:
                    with b.switch("m_size") as sw:
                        with sw.case("0"):
                            b.comment("nothing to say")
                        with sw.default():
                            b.line("(void) m_size;")

            with c.private("Member variables"):
                c.var("U32", "CAPACITY", init="64", static=True, constexpr=True)
                c.var("U32", "m_data", array="CAPACITY")
                c.var("U32", "m_head")
                c.var("U32", "m_size")
                c.var("U32", "m_capacity", const=True)

    assert_compiles(d.files())


class TestAttributes:
    """The builder side of declaration attributes."""

    VISIBLE = '__attribute__((visibility("default")))'

    def test_a_single_string_is_one_attribute_not_a_sequence_of_letters(self) -> None:
        d = doc()
        d.class_("C", attributes=self.VISIBLE)
        assert f"class {self.VISIBLE} C {{" in d.render_hpp()

    def test_a_sequence_is_taken_in_order(self) -> None:
        d = doc()
        d.class_("C", attributes=["[[a]]", "[[b]]"])
        assert "class [[a]] [[b]] C {" in d.render_hpp()

    def test_a_struct_takes_them(self) -> None:
        d = doc()
        d.struct_("S", attributes="[[a]]")
        assert "struct [[a]] S {" in d.render_hpp()

    def test_a_nested_class_takes_them(self) -> None:
        d = doc()
        with d.class_("Outer") as cls:
            cls.class_("Inner", attributes="[[a]]")
        assert "class [[a]] Inner {" in d.render_hpp()

    def test_a_free_function_takes_them(self) -> None:
        d = doc()
        d.function("f", attributes="[[nodiscard]]", ret="U32", body="return 0;")
        assert "[[nodiscard]] U32 f();" in d.render_hpp()

    def test_a_member_function_takes_them(self) -> None:
        d = doc()
        with d.class_("C") as cls:
            cls.function("f", attributes="[[nodiscard]]", ret="U32", body="return 0;")
        assert "[[nodiscard]] U32 f();" in d.render_hpp()

    def test_an_exported_class_keeps_its_qualified_definitions_clean(self) -> None:
        # The whole point of a separate field: the name stays usable everywhere.
        d = doc()
        d.include("T.hpp", output=Output.CPP)
        with d.class_("C", attributes=self.VISIBLE) as cls:
            with cls.public():
                cls.constructor(body="")
                cls.destructor(body="")
                cls.function("f", ret="int", body="return 0;")
        cpp = d.render_cpp()
        assert self.VISIBLE not in cpp
        assert_compiles(d.files())


