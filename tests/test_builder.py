class TestDecorationPlacementAcrossFiles:
    """A banner or guard must land where the members it decorates actually went.

    A single decoration pinned to no file lands in the default source file, which
    is wrong twice over when the members went elsewhere: it heads nothing where it
    appears, and is missing where it is needed.  For a guard that is worse than
    untidy -- the definition compiles unguarded.
    """

    def test_a_banner_follows_its_members_to_a_supplemental_file(self) -> None:
        d = doc()
        with d.class_("C") as c:
            with c.public("Helpers"):
                with d.cpp_file("Other"):
                    c.function("f", body="a();")
        assert "Helpers" not in d.render_cpp()
        other = d.render_cpp("Other")
        assert "Helpers" in other
        assert other.index("Helpers") < other.index("a();")

    def test_a_banner_prefers_the_default_file_when_it_has_any_members(self) -> None:
        # One copy suffices for decoration.
        d = doc()
        with d.class_("C") as c:
            with c.public("Helpers"):
                c.function("here", body="a();")
                with d.cpp_file("Other"):
                    c.function("there", body="b();")
        assert "Helpers" in d.render_cpp()
        assert "Helpers" not in d.render_cpp("Other")

    def test_a_guard_follows_its_members_to_a_supplemental_file(self) -> None:
        d = doc()
        with d.class_("C") as c:
            with c.if_directive("#ifdef BUILD_UT"):
                with d.cpp_file("Other"):
                    c.function("f", body="a();")
        assert "BUILD_UT" not in d.render_cpp()
        other = d.render_cpp("Other")
        assert other.index("#ifdef BUILD_UT") < other.index("a();")
        assert other.index("a();") < other.index("#endif")

    def test_a_guard_is_repeated_into_every_file_it_needs_to_cover(self) -> None:
        d = doc()
        with d.class_("C") as c:
            with c.if_directive("#ifdef BUILD_UT"):
                c.function("here", body="a();")
                with d.cpp_file("Other"):
                    c.function("there", body="b();")
        for target, body in ((None, "a();"), ("Other", "b();")):
            out = d.render_cpp(target)
            assert out.count("#ifdef BUILD_UT") == 1
            assert out.count("#endif") == 1
            assert out.index("#ifdef BUILD_UT") < out.index(body) < out.index("#endif")

    def test_a_header_only_guard_stays_out_of_the_sources(self) -> None:
        d = doc()
        with d.class_("C") as c:
            with c.if_directive("#ifdef BUILD_UT"):
                c.function("f", pure_virtual=True)
        assert "#ifdef BUILD_UT" in d.render_hpp()
        assert "BUILD_UT" not in d.render_cpp()

    def test_a_guard_covers_a_definition_added_after_the_block_closed(self) -> None:
        # Placement is resolved at build time.
        d = doc()
        with d.class_("C") as c:
            with c.if_directive("#ifdef BUILD_UT"):
                fn = c.function("f")
        fn.body.line("a();")
        cpp = d.render_cpp()
        assert cpp.index("#ifdef BUILD_UT") < cpp.index("a();") < cpp.index("#endif")
